#!/usr/bin/env python3
"""
SVG -> Android VectorDrawable converter for the ShadeTube design handoff.

Handles the subset the designer's files use (and a bit more):
  * elements: svg, g, path, rect (rx/ry), circle, ellipse, line, polyline, polygon, text/tspan (glyphs -> paths
    with fontTools, needs the font files), defs/linearGradient (objectBoundingBox or userSpaceOnUse)
  * presentation attributes + inheritance: fill, stroke, stroke-width, stroke-linecap, stroke-linejoin,
    stroke-miterlimit, fill-rule, opacity / fill-opacity / stroke-opacity, `style="..."`
  * transform lists (translate, scale, rotate, matrix-free subset) -> nested <group>s, one per function
  * strips the huge <metadata><c2pa:manifest> blocks

Usage:
  svg2vector.py [--tint] [--prefix P] [--font FAMILY=path.ttf ...] OUT_DIR file.svg [file.svg ...]
  --tint      every color (incl. currentColor / #000) becomes @android:color/black; Compose tints it via
              Icon(tint=...) / ColorFilter. Use for the icon set.
  --name N    output file name (single input only), default: <prefix><basename with - -> _>.xml

The crescent brand mark is generated by `crescent` (exact geometry: big circle minus offset circle minus the dot),
because the designer's single-path/evenodd version also fills the part of the offset circle that lies outside
the big circle.
"""
import math
import os
import re
import sys
import xml.etree.ElementTree as ET

SVG_NS = "{http://www.w3.org/2000/svg}"
INHERITED = ("fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "stroke-miterlimit",
             "fill-rule", "fill-opacity", "stroke-opacity", "font-family", "font-size", "font-weight",
             "letter-spacing", "text-anchor")

FONTS = {}  # lowercase family -> path


def fmt(v):
    s = ("%.4f" % v).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def strip_metadata(text):
    text = re.sub(r"<metadata>.*?</metadata>", "", text, flags=re.S)
    return text


def parse_color(c):
    """Returns (android color string or None, is_gradient_ref)."""
    if c is None:
        return None
    c = c.strip()
    if c in ("none", "transparent", ""):
        return None
    if c.startswith("url("):
        return c
    if c == "currentColor":
        return "#FF000000"
    if c.startswith("#"):
        h = c[1:]
        if len(h) == 3:
            h = "".join(ch * 2 for ch in h)
        if len(h) == 6:
            return "#FF" + h.upper()
        if len(h) == 8:  # CSS #RRGGBBAA -> Android #AARRGGBB
            return "#" + (h[6:8] + h[0:6]).upper()
    named = {"black": "#FF000000", "white": "#FFFFFFFF"}
    if c in named:
        return named[c]
    raise ValueError("unsupported color " + c)


def parse_style(el):
    attrs = dict(el.attrib)
    st = attrs.pop("style", None)
    if st:
        for part in st.split(";"):
            if ":" in part:
                k, v = part.split(":", 1)
                attrs[k.strip()] = v.strip()
    return attrs


def parse_transform(t):
    out = []
    for name, args in re.findall(r"(\w+)\s*\(([^)]*)\)", t or ""):
        nums = [float(x) for x in re.split(r"[\s,]+", args.strip()) if x]
        out.append((name, nums))
    return out


def transform_group_attrs(name, nums):
    if name == "translate":
        return {"android:translateX": fmt(nums[0]), "android:translateY": fmt(nums[1] if len(nums) > 1 else 0)}
    if name == "scale":
        sx = nums[0]
        sy = nums[1] if len(nums) > 1 else sx
        return {"android:scaleX": fmt(sx), "android:scaleY": fmt(sy)}
    if name == "rotate":
        a = {"android:rotation": fmt(nums[0])}
        if len(nums) == 3:
            a["android:pivotX"] = fmt(nums[1])
            a["android:pivotY"] = fmt(nums[2])
        return a
    raise ValueError("unsupported transform " + name)


# ---------------------------------------------------------------- shapes -> path data

def rect_path(x, y, w, h, rx, ry):
    if rx <= 0 and ry <= 0:
        return "M%s,%sh%sv%sh%sz" % (fmt(x), fmt(y), fmt(w), fmt(h), fmt(-w))
    if rx <= 0:
        rx = ry
    if ry <= 0:
        ry = rx
    rx = min(rx, w / 2)
    ry = min(ry, h / 2)
    return ("M%s,%s" % (fmt(x + rx), fmt(y)) +
            "h%s" % fmt(w - 2 * rx) + "a%s,%s 0 0 1 %s,%s" % (fmt(rx), fmt(ry), fmt(rx), fmt(ry)) +
            "v%s" % fmt(h - 2 * ry) + "a%s,%s 0 0 1 %s,%s" % (fmt(rx), fmt(ry), fmt(-rx), fmt(ry)) +
            "h%s" % fmt(-(w - 2 * rx)) + "a%s,%s 0 0 1 %s,%s" % (fmt(rx), fmt(ry), fmt(-rx), fmt(-ry)) +
            "v%s" % fmt(-(h - 2 * ry)) + "a%s,%s 0 0 1 %s,%s" % (fmt(rx), fmt(ry), fmt(rx), fmt(-ry)) + "z")


def ellipse_path(cx, cy, rx, ry):
    return ("M%s,%s" % (fmt(cx - rx), fmt(cy)) +
            "a%s,%s 0 1 0 %s,0" % (fmt(rx), fmt(ry), fmt(2 * rx)) +
            "a%s,%s 0 1 0 %s,0z" % (fmt(rx), fmt(ry), fmt(-2 * rx)))


def num(a, k, d=0.0):
    v = a.get(k)
    if v is None:
        return d
    return float(re.sub(r"(px|dp)$", "", v))


# ---------------------------------------------------------------- crescent (brand mark, 64-unit space)

def circle_intersections(c0, r0, c1, r1):
    dx, dy = c1[0] - c0[0], c1[1] - c0[1]
    d = math.hypot(dx, dy)
    a = (r0 * r0 - r1 * r1 + d * d) / (2 * d)
    h = math.sqrt(max(r0 * r0 - a * a, 0))
    mx, my = c0[0] + a * dx / d, c0[1] + a * dy / d
    px, py = -dy / d, dx / d
    return (mx + h * px, my + h * py), (mx - h * px, my - h * py)


def angle(c, p):
    return math.degrees(math.atan2(p[1] - c[1], p[0] - c[0]))


def crescent():
    """Big circle (32,32) r26 minus offset circle (41,26) r21 minus the 'record hole' dot (24,38) r5."""
    B, R = (32.0, 32.0), 26.0
    S, r = (41.0, 26.0), 21.0
    D, dr = (24.0, 38.0), 5.0
    i1, i2 = circle_intersections(B, R, S, r)
    # P_top = the intersection with smaller y
    p_top, p_right = (i1, i2) if i1[1] < i2[1] else (i2, i1)
    j1, j2 = circle_intersections(S, r, D, dr)
    # order along S with increasing angle starting at p_right
    a0 = angle(S, p_right)

    def rel(p):
        return (angle(S, p) - a0) % 360

    q_first, q_second = (j1, j2) if rel(j1) < rel(j2) else (j2, j1)

    def pt(p):
        return "%s,%s" % (fmt(p[0]), fmt(p[1]))

    def arc(rad, large, sweep, p):
        return "A%s,%s 0 %d %d %s" % (fmt(rad), fmt(rad), large, sweep, pt(p))

    def span(c, p, q, sweep):
        a, b = angle(c, p), angle(c, q)
        return ((b - a) % 360) if sweep == 1 else ((a - b) % 360)

    d = "M" + pt(p_top)
    d += arc(R, 1 if span(B, p_top, p_right, 0) > 180 else 0, 0, p_right)  # outer rim, counter-clockwise
    d += arc(r, 1 if span(S, p_right, q_first, 1) > 180 else 0, 1, q_first)  # inner edge
    d += arc(dr, 1 if span(D, q_first, q_second, 1) > 180 else 0, 1, q_second)  # around the dot
    d += arc(r, 1 if span(S, q_second, p_top, 1) > 180 else 0, 1, p_top)
    return d + "Z"


# ---------------------------------------------------------------- text -> glyph paths (fontTools)

def text_paths(el, inherited):
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
    from fontTools.ttLib import TTFont

    base = dict(inherited)
    base.update(parse_style(el))
    runs = []  # (text, attrs)
    if el.text and el.text.strip():
        runs.append((el.text, dict(base)))
    for ch in el:
        a = dict(base)
        a.update(parse_style(ch))
        if ch.text:
            runs.append((ch.text, a))
        if ch.tail and ch.tail.strip():
            runs.append((ch.tail, dict(base)))
    fam = base.get("font-family", "").split(",")[0].strip().strip("'\"").lower()
    if fam not in FONTS:
        raise ValueError("no font for family '%s' (use --font)" % fam)
    font = TTFont(FONTS[fam])
    cmap = font.getBestCmap()
    upm = font["head"].unitsPerEm
    axes = {a.axisTag: (a.minValue, a.maxValue) for a in font["fvar"].axes} if "fvar" in font else {}
    size = num(base, "font-size", 16)
    ls = num(base, "letter-spacing", 0)
    scale = size / upm

    laid = []  # (glyphName, glyphset, x, fill)
    x = 0.0
    for text, a in runs:
        loc = {}
        if "wght" in axes:
            w = float(a.get("font-weight", "400").replace("normal", "400").replace("bold", "700"))
            loc["wght"] = min(max(w, axes["wght"][0]), axes["wght"][1])
        if "opsz" in axes:
            loc["opsz"] = min(max(size, axes["opsz"][0]), axes["opsz"][1])
        gs = font.getGlyphSet(location=loc) if loc else font.getGlyphSet()
        fill = a.get("fill", "#000")
        for ch in text:
            g = cmap.get(ord(ch))
            if g is None:
                continue
            laid.append((g, gs, x, fill))
            x += gs[g].width * scale + ls
    total = x - ls
    x0 = num(base, "x")
    y0 = num(base, "y")
    anchor = base.get("text-anchor", "start")
    if anchor == "middle":
        x0 -= total / 2
    elif anchor == "end":
        x0 -= total
    by_fill = {}
    for g, gs, gx, fill in laid:
        pen = SVGPathPen(gs, ntos=fmt)
        gs[g].draw(TransformPen(pen, (scale, 0, 0, -scale, x0 + gx, y0)))
        by_fill.setdefault(fill, []).append(pen.getCommands())
    return [(fill, "".join(cmds)) for fill, cmds in by_fill.items()]


# ---------------------------------------------------------------- converter

class Converter:
    def __init__(self, tint):
        self.tint = tint
        self.gradients = {}
        self.out = []
        self.depth = 1

    def emit(self, s):
        self.out.append("    " * self.depth + s)

    def color(self, c, bbox):
        c = parse_color(c)
        if c is None:
            return None
        if self.tint:
            return "@android:color/black"
        if c.startswith("url("):
            gid = re.match(r"url\(#([^)]+)\)", c).group(1)
            return ("gradient", self.gradients[gid], bbox)
        return c

    def collect_gradients(self, root):
        for g in root.iter(SVG_NS + "linearGradient"):
            a = parse_style(g)
            stops = []
            for s in g.iter(SVG_NS + "stop"):
                sa = parse_style(s)
                off = sa.get("offset", "0")
                off = float(off[:-1]) / 100 if off.endswith("%") else float(off)
                stops.append((off, parse_color(sa.get("stop-color", "#000"))))
            self.gradients[a["id"]] = dict(
                x1=float(a.get("x1", 0)), y1=float(a.get("y1", 0)), x2=float(a.get("x2", 1)), y2=float(a.get("y2", 0)),
                units=a.get("gradientUnits", "objectBoundingBox"), stops=stops)

    def path(self, d, a, bbox, extra_fill_default=True):
        fill = a.get("fill", "#000000" if extra_fill_default else "none")
        stroke = a.get("stroke", "none")
        fc = self.color(fill, bbox)
        sc = self.color(stroke, bbox)
        attrs = ['android:pathData="%s"' % d]
        grad = None
        if isinstance(fc, tuple):
            grad = fc
        elif fc:
            attrs.append('android:fillColor="%s"' % fc)
        if "fill-opacity" in a and fc:
            attrs.append('android:fillAlpha="%s"' % a["fill-opacity"])
        if a.get("fill-rule") == "evenodd":
            attrs.append('android:fillType="evenOdd"')
        if sc:
            if isinstance(sc, tuple):
                raise ValueError("gradient strokes unsupported")
            attrs.append('android:strokeColor="%s"' % sc)
            attrs.append('android:strokeWidth="%s"' % fmt(num(a, "stroke-width", 1)))
            if a.get("stroke-linecap") in ("round", "square"):
                attrs.append('android:strokeLineCap="%s"' % a["stroke-linecap"])
            if a.get("stroke-linejoin") in ("round", "bevel"):
                attrs.append('android:strokeLineJoin="%s"' % a["stroke-linejoin"])
            if "stroke-miterlimit" in a:
                attrs.append('android:strokeMiterLimit="%s"' % a["stroke-miterlimit"])
            if "stroke-opacity" in a:
                attrs.append('android:strokeAlpha="%s"' % a["stroke-opacity"])
        if a.get("opacity"):
            o = a["opacity"]
            if fc:
                attrs.append('android:fillAlpha="%s"' % o)
            if sc:
                attrs.append('android:strokeAlpha="%s"' % o)
        self.emit("<path")
        for x in attrs[:-1]:
            self.emit("    " + x)
        if grad is None:
            self.emit("    " + attrs[-1] + " />")
            return
        self.emit("    " + attrs[-1] + ">")
        _, g, (bx, by, bw, bh) = grad
        if g["units"] == "objectBoundingBox":
            sx, sy, ex, ey = bx + g["x1"] * bw, by + g["y1"] * bh, bx + g["x2"] * bw, by + g["y2"] * bh
        else:
            sx, sy, ex, ey = g["x1"], g["y1"], g["x2"], g["y2"]
        self.emit('    <aapt:attr name="android:fillColor">')
        self.emit('        <gradient android:type="linear" android:startX="%s" android:startY="%s" '
                  'android:endX="%s" android:endY="%s">' % (fmt(sx), fmt(sy), fmt(ex), fmt(ey)))
        for off, col in g["stops"]:
            self.emit('            <item android:offset="%s" android:color="%s" />' % (fmt(off), col))
        self.emit("        </gradient>")
        self.emit("    </aapt:attr>")
        self.emit("</path>")

    def node(self, el, inherited, viewport):
        tag = el.tag.replace(SVG_NS, "")
        if tag in ("defs", "metadata", "title", "desc", "linearGradient", "stop"):
            return
        a = dict(inherited)
        own = parse_style(el)
        for k in INHERITED:
            if k in own:
                a[k] = own[k]
        for k in ("opacity",):
            if k in own:
                a[k] = own[k]
        transforms = parse_transform(own.get("transform"))
        for name, nums in transforms:
            ga = transform_group_attrs(name, nums)
            self.emit("<group " + " ".join('%s="%s"' % kv for kv in ga.items()) + ">")
            self.depth += 1
        if tag in ("svg", "g"):
            for ch in el:
                self.node(ch, a, viewport)
        elif tag == "path":
            self.path(own["d"].strip(), a, viewport)
        elif tag == "rect":
            x, y, w, h = num(own, "x"), num(own, "y"), num(own, "width"), num(own, "height")
            rx = num(own, "rx", -1)
            ry = num(own, "ry", -1)
            if rx < 0 and ry >= 0:
                rx = ry
            if ry < 0 and rx >= 0:
                ry = rx
            self.path(rect_path(x, y, w, h, max(rx, 0), max(ry, 0)), a, (x, y, w, h))
        elif tag == "circle":
            cx, cy, r = num(own, "cx"), num(own, "cy"), num(own, "r")
            self.path(ellipse_path(cx, cy, r, r), a, (cx - r, cy - r, 2 * r, 2 * r))
        elif tag == "ellipse":
            cx, cy, rx, ry = num(own, "cx"), num(own, "cy"), num(own, "rx"), num(own, "ry")
            self.path(ellipse_path(cx, cy, rx, ry), a, (cx - rx, cy - ry, 2 * rx, 2 * ry))
        elif tag == "line":
            d = "M%s,%sL%s,%s" % (fmt(num(own, "x1")), fmt(num(own, "y1")), fmt(num(own, "x2")), fmt(num(own, "y2")))
            self.path(d, dict(a, fill="none"), viewport)
        elif tag in ("polyline", "polygon"):
            pts = [float(v) for v in re.split(r"[\s,]+", own["points"].strip()) if v]
            d = "M" + " L".join("%s,%s" % (fmt(pts[i]), fmt(pts[i + 1])) for i in range(0, len(pts), 2))
            if tag == "polygon":
                d += "Z"
                self.path(d, a, viewport)
            else:
                self.path(d, dict(a, fill=a.get("fill", "none")), viewport)
        elif tag == "text":
            for fill, d in text_paths(el, a):
                self.path(d, dict(a, fill=fill, stroke="none"), viewport)
        else:
            raise ValueError("unsupported element <%s>" % tag)
        for _ in transforms:
            self.depth -= 1
            self.emit("</group>")

    def convert(self, svg_text):
        root = ET.fromstring(strip_metadata(svg_text))
        self.collect_gradients(root)
        ra = parse_style(root)
        vb = [float(v) for v in re.split(r"[\s,]+", ra.get("viewBox", "").strip()) if v] or \
             [0, 0, num(ra, "width"), num(ra, "height")]
        w = num(ra, "width", vb[2])
        h = num(ra, "height", vb[3])
        if vb[0] or vb[1]:
            self.emit('<group android:translateX="%s" android:translateY="%s">' % (fmt(-vb[0]), fmt(-vb[1])))
            self.depth += 1
        for ch in root:
            self.node(ch, {}, (vb[0], vb[1], vb[2], vb[3]))
        if vb[0] or vb[1]:
            self.depth -= 1
            self.emit("</group>")
        body = "\n".join(self.out)
        ns = ' xmlns:aapt="http://schemas.android.com/aapt"' if "aapt:attr" in body else ""
        return ('<?xml version="1.0" encoding="utf-8"?>\n'
                '<!-- Generated by tools/svg2vector.py from the design handoff. Do not edit by hand. -->\n'
                '<vector xmlns:android="http://schemas.android.com/apk/res/android"%s\n'
                '    android:width="%sdp"\n    android:height="%sdp"\n'
                '    android:viewportWidth="%s"\n    android:viewportHeight="%s">\n%s\n</vector>\n'
                % (ns, fmt(w), fmt(h), fmt(vb[2]), fmt(vb[3]), body))


def mark_vector(size_dp, viewport, tx, ty, scale, color, extra_bg=None):
    """Crescent brand mark inside a square viewport (designer transform: translate(tx,ty) scale(scale))."""
    bg = ""
    if extra_bg:
        bg = extra_bg
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tools/svg2vector.py (crescent = big circle - offset circle - dot). -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="%sdp"\n    android:height="%sdp"\n'
            '    android:viewportWidth="%s"\n    android:viewportHeight="%s">\n%s'
            '    <group android:translateX="%s" android:translateY="%s" android:scaleX="%s" android:scaleY="%s">\n'
            '        <path android:fillColor="%s"\n            android:pathData="%s" />\n'
            '    </group>\n</vector>\n'
            % (fmt(size_dp), fmt(size_dp), fmt(viewport), fmt(viewport), bg, fmt(tx), fmt(ty), fmt(scale), fmt(scale),
               color, crescent()))


def main(argv):
    tint = False
    prefix = ""
    name = None
    files = []
    out_dir = None
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "--tint":
            tint = True
        elif a == "--prefix":
            i += 1
            prefix = argv[i]
        elif a == "--name":
            i += 1
            name = argv[i]
        elif a == "--font":
            i += 1
            fam, path = argv[i].split("=", 1)
            FONTS[fam.lower()] = path
        elif a == "--crescent":
            # --crescent OUT size viewport tx ty scale color
            out, size, vp, tx, ty, sc, col = argv[i + 1:i + 8]
            i += 7
            with open(out, "w", encoding="utf-8", newline="\n") as f:
                f.write(mark_vector(float(size), float(vp), float(tx), float(ty), float(sc), col))
            print("wrote", out)
        elif out_dir is None:
            out_dir = a
        else:
            files.append(a)
        i += 1
    for f in files:
        base = os.path.splitext(os.path.basename(f))[0].replace("-", "_").lower()
        dest = os.path.join(out_dir, (name or (prefix + base)) + ".xml")
        with open(f, encoding="utf-8") as fh:
            xml = Converter(tint).convert(fh.read())
        with open(dest, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(xml)
        print("wrote", dest)


if __name__ == "__main__":
    main(sys.argv[1:])
